// Records /demo: shopper intent -> agents negotiate -> PayPal Sandbox approval -> Rosa's phone.
// Usage: PP_EMAIL=... PP_PASS=... node scripts/shop.cjs <outdir> [intentIndex]
const { chromium } = require('playwright');
const { startRec } = require('./rec.cjs');
const out = process.argv[2] || 'raw/shop1';
const W = 1440, H = 810, DSF = 4 / 3;
const log = (...a) => console.log(new Date().toISOString().slice(11, 19), ...a);
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: W, height: H }, deviceScaleFactor: DSF });
  const p = await ctx.newPage();
  await p.goto('https://jomm.onrender.com/demo', { waitUntil: 'networkidle' });
  // finish Act 1 quickly (not recorded here)
  await p.getByText('▶ Play Rosa’s video').click();
  await p.waitForTimeout(500);
  await p.getByText('Skip ›').click();
  await p.waitForTimeout(1500);
  await p.locator('section[aria-label="Shopper’s agent"]').scrollIntoViewIfNeeded();
  await p.evaluate(() => window.scrollBy(0, -80));
  await p.waitForTimeout(800);
  const rec = await startRec(p, `${out}/main`);
  const t0 = Date.now(); const mark = (m) => log(((Date.now() - t0) / 1000).toFixed(1) + 's', m);
  await p.waitForTimeout(1500);
  const box = p.getByLabel('What should the shopper’s agent buy?');
  await box.click();
  await box.pressSequentially('Strawberries for a party tonight. 3 boxes, keep it under $17.', { delay: 45 });
  mark('typed');
  await p.waitForTimeout(800);
  await p.getByText('Send the shopper’s agent').click();
  mark('sent');
  // wait for PayPal buttons
  const ppFrame = p.frameLocator('iframe[title*="PayPal"]').first();
  const ppBtn = ppFrame.locator('[data-funding-source="paypal"]').first();
  await ppBtn.waitFor({ timeout: 240000 });
  mark('paypal button visible');
  await p.screenshot({ path: `${out}/before-pay.png` });
  await p.waitForTimeout(3000);
  const [pop] = await Promise.all([ctx.waitForEvent('page'), ppBtn.click()]);
  mark('popup');
  await pop.setViewportSize({ width: 1440, height: 810 }).catch(() => {});
  const prec = await startRec(pop, `${out}/popup`);
  await pop.waitForLoadState('domcontentloaded');
  const email = pop.locator('#email');
  await email.waitFor({ timeout: 60000 });
  await email.click(); await email.pressSequentially(process.env.PP_EMAIL, { delay: 30 });
  const next = pop.locator('#btnNext');
  if (await next.isVisible().catch(() => false)) await next.click();
  const pw = pop.locator('#password');
  await pw.waitFor({ timeout: 30000 });
  await pw.click(); await pw.fill(process.env.PP_PASS);
  await pop.waitForTimeout(600);
  await pop.locator('#btnLogin').click();
  mark('logged in');
  const pay = pop.locator('[data-id="payment-submit-btn"], #payment-submit-btn, button:has-text("Complete Purchase"), button:has-text("Continue"), button:has-text("Pay")').first();
  await pay.waitFor({ timeout: 90000 });
  await pop.waitForTimeout(2500);
  await pop.screenshot({ path: `${out}/review.png` });
  await pay.click();
  mark('approved');
  await pop.waitForEvent('close', { timeout: 60000 }).catch(() => log('popup did not close'));
  await prec.stop().catch(() => {});
  await p.getByText('Paid. Rosa’s phone just buzzed').waitFor({ timeout: 90000 });
  mark('paid');
  await p.waitForTimeout(12000);
  mark('end');
  await p.screenshot({ path: `${out}/after.png` });
  await p.screenshot({ path: `${out}/after-full.png`, fullPage: true });
  log('frames', await rec.stop());
  await b.close();
})().catch(async (e) => { console.error(e); process.exit(1); });
